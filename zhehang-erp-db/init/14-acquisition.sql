DROP TABLE IF EXISTS `acq_enterprise`;
CREATE TABLE `acq_enterprise` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '企业ID',
    `company_name` VARCHAR(200) NOT NULL COMMENT '企业名称',
    `credit_code` VARCHAR(30) DEFAULT NULL COMMENT '统一社会信用代码',
    `legal_person` VARCHAR(50) DEFAULT NULL COMMENT '法定代表人',
    `register_region_province` VARCHAR(50) DEFAULT NULL COMMENT '注册省份',
    `register_region_city` VARCHAR(50) DEFAULT NULL COMMENT '注册城市',
    `register_region_district` VARCHAR(50) DEFAULT NULL COMMENT '注册区县',
    `register_address` VARCHAR(500) DEFAULT NULL COMMENT '注册地址',
    `establishment_date` DATE DEFAULT NULL COMMENT '成立日期',
    `registered_capital` DECIMAL(15,2) DEFAULT NULL COMMENT '注册资本(万元)',
    `paid_capital` DECIMAL(15,2) DEFAULT NULL COMMENT '实缴资本(万元)',
    `enterprise_type` VARCHAR(50) DEFAULT NULL COMMENT '企业类型',
    `industry_code` VARCHAR(20) DEFAULT NULL COMMENT '行业代码',
    `industry_name` VARCHAR(100) DEFAULT NULL COMMENT '行业名称',
    `business_scope` TEXT COMMENT '经营范围',
    `staff_count_min` INT DEFAULT NULL COMMENT '人员规模下限',
    `staff_count_max` INT DEFAULT NULL COMMENT '人员规模上限',
    `annual_revenue` DECIMAL(15,2) DEFAULT NULL COMMENT '年营业额(万元)',
    `enterprise_status` VARCHAR(20) DEFAULT '在业' COMMENT '经营状态(在业/存续/迁入/迁出/停业/清算/吊销/注销)',
    `tax_qualification` VARCHAR(30) DEFAULT NULL COMMENT '纳税资质(一般纳税人/小规模纳税人/疑似小规模纳税人)',
    `tax_abnormal_status` VARCHAR(30) DEFAULT 'normal' COMMENT '税务非正常户状态(normal/非正常户/非正常户注销/解除非正常)',
    `has_tax_arrears` TINYINT(1) DEFAULT 0 COMMENT '是否有欠税公告',
    `tax_arrears_amount` DECIMAL(15,2) DEFAULT 0 COMMENT '欠税金额(元)',
    `has_major_tax_violation` TINYINT(1) DEFAULT 0 COMMENT '是否有重大税收违法',
    `has_tax_penalty` TINYINT(1) DEFAULT 0 COMMENT '是否有税务行政处罚',
    `is_in_abnormal_operation_list` TINYINT(1) DEFAULT 0 COMMENT '是否在经营异常名录',
    `pending_abnormal_count` INT DEFAULT 0 COMMENT '当前待处理异常数',
    `contact_count` INT DEFAULT 0 COMMENT '可解锁联系方式数量',
    `has_contact` TINYINT(1) DEFAULT 0 COMMENT '是否有联系方式',
    `enterprise_risk_score` INT DEFAULT 0 COMMENT '企业风险评分(0-100)',
    `ai_potential_score` INT DEFAULT 0 COMMENT 'AI潜力评分(0-100)',
    `is_hot` TINYINT(1) DEFAULT 0 COMMENT '是否HOT标记',
    `business_term_type` VARCHAR(20) DEFAULT NULL COMMENT '营业期限类型(长期/固定期限)',
    `business_term_end` DATE DEFAULT NULL COMMENT '营业期限到期日',
    `annual_report_status` VARCHAR(20) DEFAULT NULL COMMENT '年报状态(已提交/未提交/已逾期/免报)',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `create_by` BIGINT DEFAULT NULL COMMENT '创建人',
    `update_by` BIGINT DEFAULT NULL COMMENT '更新人',
    `deleted` TINYINT(1) DEFAULT 0 COMMENT '是否删除：0否 1是',
    `tenant_id` BIGINT DEFAULT NULL COMMENT '租户ID',
    PRIMARY KEY (`id`),
    KEY `idx_credit_code` (`credit_code`),
    KEY `idx_enterprise_status` (`enterprise_status`),
    KEY `idx_tax_qualification` (`tax_qualification`),
    KEY `idx_register_region_city` (`register_region_city`),
    KEY `idx_establishment_date` (`establishment_date`),
    KEY `idx_ai_potential_score` (`ai_potential_score`),
    KEY `idx_tenant_id` (`tenant_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='企业主数据表';

